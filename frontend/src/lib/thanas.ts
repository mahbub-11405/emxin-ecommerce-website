export const DIVISION_OF:Record<string,string>=Object.fromEntries(Object.entries(DIV).flatMap(([d,ds])=>ds.map(x=>[x,d])));

export type Place={thana:string;district:string;division:string};
// old / English spellings people type for districts
const ALIAS:Record<string,string>={chittagong:'chattogram',ctg:'chattogram',comilla:'cumilla',barisal:'barishal',bogra:'bogura',jessore:'jashore'};
const norm=(s:string)=>s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]/g,'');
/** sound-alike key, so "monohordi" finds "Monohardi" and "chokbazar" finds "Chawkbazar" */
const skel=(s:string)=>norm(s).replace(/ph/g,'f').replace(/[aeiouhwy]/g,'').replace(/(.)\1+/g,'$1');
const ALL:Place[]=Object.entries(THANAS).flatMap(([district,ts])=>ts.map(thana=>({thana,district,division:DIVISION_OF[district]||''})));
const IDX=ALL.map(p=>({p,n:norm(p.thana),w:p.thana.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean),k:skel(p.thana),d:norm(p.district)}));
/** Thanas matching what the customer typed (a few letters are enough), best first: name start, word start, inside the name,
 *  sound-alike, then the district's name ("narsingdi" lists the thanas of Narsingdi). */
export function searchThana(q:string,limit=8):Place[]{
  let n=norm(q);if(n.length<2)return [];n=ALIAS[n]||n;const k=skel(q);
  const scored:{p:Place;s:number}[]=[];
  for(const x of IDX){
    // sound-alike only from 3 consonants on ("monohordi"), so "mono" does not also bring Homna / Manda
    const s=x.n.startsWith(n)?0:x.w.some(w=>w.startsWith(n))?1:(n.length>=3&&x.n.includes(n))?2:(k.length>=3&&x.k.startsWith(k))?3:(n.length>=3&&x.d.startsWith(n))?4:-1;
    if(s>=0)scored.push({p:x.p,s});
  }
  return scored.sort((a,b)=>a.s-b.s||a.p.thana.length-b.p.thana.length||a.p.thana.localeCompare(b.p.thana)).slice(0,limit).map(x=>x.p);
}
export const placeLabel=(p:Place)=>`${p.thana}, ${p.district}${p.division?` · ${p.division} Division`:''}`;
